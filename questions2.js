  // ---- 푼 문제 피하기(고정 문항만) ----
  const SEEN_KEY = 'ncs9-seen';
  const loadSeen = () => { try { return new Set(JSON.parse(localStorage.getItem(SEEN_KEY) || '[]')); } catch (e) { return new Set(); } };
  const saveSeen = (s) => { try { localStorage.setItem(SEEN_KEY, JSON.stringify([...s].slice(-600))); } catch (e) {} };
  function takeUnseen(list, n, seen) {
    const fixed = (q) => !/^g/.test(q.id);
    let fresh = shuffle(list.filter((q) => !fixed(q) || !seen.has(q.id)));
    if (fresh.length < n) { // 다 풀었으면 이 목록의 기록만 초기화
      list.forEach((q) => seen.delete(q.id));
      fresh = shuffle(list);
    }
    const out = fresh.slice(0, n);
    out.forEach((q) => { if (fixed(q)) seen.add(q.id); });
    return out;
  }

