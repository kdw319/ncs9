  const PTS_W = { comm: [.1, .4, .5], math: [.1, .3, .6], ps: [.1, .3, .6], org: [.4, .5, .1], info: [.3, .5, .2], res: [.2, .5, .3], tech: [.5, .4, .1], self: [.5, .4, .1], inter: [.4, .5, .1], ethic: [.6, .35, .05] };
  const weigh = (key) => { const w = PTS_W[key], r = Math.random(); return r < w[0] ? 0.8 : r < w[0] + w[1] ? 1.2 : 1.5; };

